#!/usr/bin/env node
// The deliberately small schema vocabulary is checked, not silently approximated.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const schema = JSON.parse(fs.readFileSync(path.join(root, 'contracts/desktop/v1/schema.json'), 'utf8'));
const definitions = Object.entries(schema.$defs).filter(([name]) => !name.endsWith('_request') && !name.endsWith('_response'));
const pascal = name => name.split(/[^A-Za-z0-9]+/).map(word => word[0].toUpperCase() + word.slice(1)).join('');
const snake = name => name.replace(/[A-Z]/g, c => `_${c.toLowerCase()}`);
const nullable = s => !!s.anyOf?.some(item => item.type === 'null');
function type(s, language) {
  if (s.$ref) return s.$ref.split('/').pop();
  if (s.anyOf) return language === 'ts' ? s.anyOf.map(v => type(v, language)).join(' | ') : `Option<${type(s.anyOf.find(v => v.type !== 'null'), language)}>`;
  if (s.enum && language === 'ts') return s.enum.map(v => JSON.stringify(v)).join(' | ');
  if (s.const !== undefined && language === 'ts') return JSON.stringify(s.const);
  switch (s.type) {
    case 'null': return 'null';
    case 'string': return language === 'ts' ? 'string' : 'String';
    case 'integer': return language === 'ts' ? 'number' : 'i64';
    case 'boolean': return language === 'ts' ? 'boolean' : 'bool';
    case 'array': return language === 'ts' ? `Array<${type(s.items, language)}>` : `Vec<${type(s.items, language)}>`;
    default: throw new Error(`Unsupported schema type: ${JSON.stringify(s)}`);
  }
}
// Inline string enums/constants are emitted as named Rust enums too.
const rustDefinitions = [...definitions];
const inline = (s, name) => {
  if (s.type === 'string' && (s.enum || s.const !== undefined)) {
    rustDefinitions.push([name, { type: 'string', enum: s.enum ?? [s.const] }]);
    return { $ref: `#/$defs/${name}` };
  }
  if (s.anyOf) return { ...s, anyOf: s.anyOf.map(v => v.type === 'null' ? v : inline(v, name)) };
  if (s.type === 'array') return { ...s, items: inline(s.items, `${name}Item`) };
  return s;
};
for (const [name, s] of definitions) if (s.type === 'object') {
  const copy = { ...s, properties: Object.fromEntries(Object.entries(s.properties).map(([key, value]) => [key, inline(value, `${name}${pascal(key)}`)])) };
  rustDefinitions[rustDefinitions.findIndex(([n]) => n === name)] = [name, copy];
}
let ts = '// Generated by scripts/generate-desktop-contracts.mjs. Do not edit.\n';
let rs = '// Generated by scripts/generate-desktop-contracts.mjs. Do not edit.\nuse serde::{Deserialize, Serialize};\n';
for (const [name, s] of definitions) {
  if (s.type === 'object') {
    ts += `export interface ${name} {\n${Object.entries(s.properties).map(([k, v]) => `  ${k}${s.required.includes(k) ? '' : '?'}: ${type(v, 'ts')};`).join('\n')}\n}\n`;
  } else ts += `export type ${name} = ${type(s, 'ts')};\n`;
}
for (const [name, s] of rustDefinitions) {
  if (name === 'ErrorCode') { rs += 'pub use crate::core::contracts::ErrorCode;\n'; continue; }
  if (s.type === 'object') {
    rs += `#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]\n#[serde(rename_all = "camelCase", deny_unknown_fields)]\npub struct ${name} {\n`;
    for (const [key, value] of Object.entries(s.properties)) {
      const required = s.required.includes(key);
      if (!required) rs += nullable(value) ? '    #[serde(default, deserialize_with = "present_nullable", skip_serializing_if = "Option::is_none")]\n' : '    #[serde(default, skip_serializing_if = "Option::is_none")]\n';
      else if (nullable(value)) rs += '    #[serde(deserialize_with = "required_nullable")]\n';
      rs += `    pub ${snake(key)}: ${required ? type(value, 'rs') : `Option<${type(value, 'rs')}>`},\n`;
    }
    rs += '}\n';
  } else if (s.type === 'string' && s.enum) {
    rs += `#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]\npub enum ${name} {\n${s.enum.map(v => `    #[serde(rename = ${JSON.stringify(v)})]\n    ${/^[0-9]/.test(v) ? 'V' : ''}${pascal(v.replaceAll('.', '_'))},`).join('\n')}\n}\n`;
  } else rs += `pub type ${name} = ${type(s, 'rs')};\n`;
}
rs += `fn required_nullable<'de, D, T>(deserializer: D) -> Result<Option<T>, D::Error>\nwhere D: serde::Deserializer<'de>, T: Deserialize<'de> { Option::<T>::deserialize(deserializer) }\nfn present_nullable<'de, D, T>(deserializer: D) -> Result<Option<Option<T>>, D::Error>\nwhere D: serde::Deserializer<'de>, T: Deserialize<'de> { Option::<T>::deserialize(deserializer).map(Some) }\n`;
rs += '#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]\n#[serde(rename_all = "camelCase", deny_unknown_fields)]\npub struct Request<T> { pub schema_version: u32, pub request_id: RequestId, pub payload: T }\n';
rs += '#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]\n#[serde(rename_all = "camelCase", deny_unknown_fields)]\npub struct Success<T> { pub schema_version: u32, pub request_id: RequestId, pub data: T }\n';
rs += '#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]\n#[serde(rename_all = "camelCase", deny_unknown_fields)]\npub struct Failure { pub schema_version: u32, pub request_id: RequestId, pub error: BridgeError }\n';
rs += '#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]\n#[serde(untagged)]\npub enum Response<T> { Success(Success<T>), Failure(Failure) }\n';
ts += 'export interface Request<T> { schemaVersion: 1; requestId: RequestId; payload: T }\nexport type Response<T> = { schemaVersion: 1; requestId: RequestId; data: T } | { schemaVersion: 1; requestId: RequestId; error: BridgeError };\nexport interface DesktopCommandMap {\n';
for (const [name, c] of Object.entries(schema['x-commands'])) ts += `  ${name}: { request: ${c.request}; response: ${c.response} };\n`;
ts += '}\nexport type DesktopCommand = keyof DesktopCommandMap;\n';
ts += `export const DESKTOP_BUDGETS = ${JSON.stringify(schema['x-budgets'], null, 2)} as const;\n`;
for (const [kind, field] of [['DesktopRequest', 'request'], ['DesktopResponse', 'response']]) {
  rs += `#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]\n#[serde(tag = "command", content = "${field}", deny_unknown_fields)]\npub enum ${kind} {\n`;
  for (const [name, c] of Object.entries(schema['x-commands'])) rs += `    #[serde(rename = "${name}")]\n    ${pascal(name)}(${field === 'request' ? 'Request' : 'Response'}<${c[field]}>),\n`;
  rs += '}\n';
}
// rustfmt is part of the existing toolchain; generation never resolves dependencies.
rs = execFileSync('rustfmt', ['--edition', '2021', '--emit', 'stdout'], { input: rs, encoding: 'utf8' });
const names = `// Generated by scripts/generate-desktop-contracts.mjs. Do not edit.\npub const COMMAND_NAMES: &[&str] = &[\n${Object.keys(schema['x-commands']).map(n => `    \"${n}\",`).join('\n')}\n];\n`;
const outputs = new Map([['src/application/desktop_contracts.rs', rs], ['apps/desktop/src/contracts.generated.ts', ts], ['contracts/desktop/v1/commands.generated.rs', names]]);
let drift = false;
for (const [name, contents] of outputs) {
  const target = path.join(root, name);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== contents) { console.error(`Contract drift: ${name}`); drift = true; }
  } else { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, contents); }
}
if (drift) process.exit(1);
console.log(`Desktop v1: ${Object.keys(schema['x-commands']).length} commands, ${definitions.length} named definitions; generated files ${process.argv.includes('--check') ? 'match' : 'written'}.`);
