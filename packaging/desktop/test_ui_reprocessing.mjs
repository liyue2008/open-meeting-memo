import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
const source = readFileSync(new URL('../../scripts/fixtures/desktop-ui-probe.js', import.meta.url), 'utf8');
const prefix = source.split('// Real React events')[0];
const context = vm.createContext({});
vm.runInContext(prefix, context);
const prove = context.reprocessingEvidence;
assert.equal(typeof prove, 'function');
const task = {taskId:'new', stage:'summary'};
const version = {artifact:{taskId:'new',stage:'transcribe'},status:'committed',sourceTranscriptTaskId:null};
const text = 'PRIVATE_SYNTHETIC_TRANSCRIPT';
assert.equal(prove('transcribe', task, [version], text), true, 'fast advancement after actual worker transcription');
assert.equal(prove('transcribe', task, [{...version,sourceTranscriptTaskId:'old'}], text), false, 'summary-only reused transcript rejected');
assert.equal(prove('transcribe', task, [version], 'Private synthetic transcript token'), false, 'seed transcript without worker execution rejected');
assert.equal(prove('transcribe', task, [{...version,artifact:{taskId:'other',stage:'transcribe'}}], text), false, 'wrong generation rejected');
assert.equal(prove('transcribe', {...task,stage:'unknown'}, [version], text), false, 'undefined stage rejected');
assert.equal(prove('summary', task, [{...version,sourceTranscriptTaskId:'old'}], ''), true, 'summary request retains source');
assert.equal(prove('summary', {...task,stage:'transcribe'}, [version], text), false, 'wrong starting stage rejected');
assert.equal(prove('transcribe', {...task,stage:'transcribe'}, [{...version,status:'missing'}], ''), false, 'queued does not prove execution');
console.log('8 source-bound reprocessing assertions passed');
